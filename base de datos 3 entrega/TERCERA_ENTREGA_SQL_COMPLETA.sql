CREATE OR REPLACE TRIGGER TRG_ACTUALIZAR_CUPOS_ENTIDAD_AI
AFTER INSERT ON practica
FOR EACH ROW
BEGIN
  UPDATE entidad_receptora
     SET cupos_disponibles = GREATEST(cupos_disponibles - 1, 0)
   WHERE id_entidad = :NEW.id_entidad;
END;
/

CREATE OR REPLACE TRIGGER TRG_RESTAURAR_CUPOS_ENTIDAD_AD
AFTER DELETE ON practica
FOR EACH ROW
BEGIN
  UPDATE entidad_receptora
     SET cupos_disponibles = LEAST(cupos_disponibles + 1, cupos_totales)
   WHERE id_entidad = :OLD.id_entidad;
END;
/

