PROMPT 2.4) PROCEDIMIENTOS ALMACENADOS

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_ACTIVIDAD (
  P_ID_PRACTICA       IN  NUMBER,
  P_FECHA_ACTIVIDAD   IN  DATE,
  P_DESCRIPCION       IN  VARCHAR2,
  P_HORAS             IN  NUMBER,
  P_ID_ACTIVIDAD_OUT  OUT NUMBER
) IS
BEGIN
  INSERT INTO actividad_practica (
    id_actividad, fecha_actividad, descripcion, horas, estado_validacion, comentario_docente, id_practica
  ) VALUES (
    NULL, P_FECHA_ACTIVIDAD, P_DESCRIPCION, P_HORAS, 'PENDIENTE', NULL, P_ID_PRACTICA
  )
  RETURNING id_actividad INTO P_ID_ACTIVIDAD_OUT;

  UPDATE practica
     SET horas_acumuladas = NVL(horas_acumuladas, 0) + P_HORAS,
         estado = CASE
                    WHEN NVL(horas_acumuladas, 0) + P_HORAS >= horas_objetivo THEN 'FINALIZADA'
                    ELSE estado
                  END
   WHERE id_practica = P_ID_PRACTICA;
END;
/

CREATE OR REPLACE PROCEDURE SP_VALIDAR_ACTIVIDAD (
  P_ID_ACTIVIDAD      IN NUMBER,
  P_ESTADO_VALIDACION IN VARCHAR2,
  P_COMENTARIO        IN VARCHAR2
) IS
BEGIN
  UPDATE actividad_practica
     SET estado_validacion = P_ESTADO_VALIDACION,
         comentario_docente = P_COMENTARIO
   WHERE id_actividad = P_ID_ACTIVIDAD;
END;
/

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_JORNADA (
  P_ID_PRACTICA         IN  NUMBER,
  P_FECHA_JORNADA       IN  DATE,
  P_HORA_INGRESO        IN  VARCHAR2,
  P_HORA_SALIDA         IN  VARCHAR2,
  P_FIRMA_INGRESO       IN  VARCHAR2,
  P_FIRMA_SALIDA        IN  VARCHAR2,
  P_CARGO_FIRMANTE      IN  VARCHAR2,
  P_OBSERVACION         IN  VARCHAR2,
  P_ID_JORNADA_OUT      OUT NUMBER
) IS
  V_HORAS NUMBER;
BEGIN
  V_HORAS := ROUND((
    TO_DATE(P_HORA_SALIDA, 'HH24:MI') - TO_DATE(P_HORA_INGRESO, 'HH24:MI')
  ) * 24, 2);

  INSERT INTO jornada_practica (
    id_jornada, id_practica, fecha_jornada, hora_ingreso, hora_salida,
    horas_registradas, firma_ingreso_nombre, firma_salida_nombre,
    cargo_firmante, estado_validacion, observacion
  ) VALUES (
    NULL, P_ID_PRACTICA, P_FECHA_JORNADA, P_HORA_INGRESO, P_HORA_SALIDA,
    V_HORAS, P_FIRMA_INGRESO, P_FIRMA_SALIDA,
    P_CARGO_FIRMANTE, 'PENDIENTE', P_OBSERVACION
  )
  RETURNING id_jornada INTO P_ID_JORNADA_OUT;
END;
/

CREATE OR REPLACE PROCEDURE SP_CERRAR_PRACTICA (
  P_ID_PRACTICA   IN NUMBER,
  P_ESTADO_FINAL  IN VARCHAR2
) IS
BEGIN
  UPDATE practica
     SET estado = P_ESTADO_FINAL,
         fecha_fin = NVL(fecha_fin, SYSDATE)
   WHERE id_practica = P_ID_PRACTICA;
END;
/

