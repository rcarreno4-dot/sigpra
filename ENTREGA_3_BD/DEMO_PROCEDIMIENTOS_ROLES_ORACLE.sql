PROMPT 4) PROCEDIMIENTOS ALMACENADOS

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_ACTIVIDAD (
  P_ID_PRACTICA       IN  NUMBER,
  P_FECHA_ACTIVIDAD   IN  DATE,
  P_ACTIVIDAD         IN  VARCHAR2,
  P_DESCRIPCION       IN  VARCHAR2,
  P_HORAS             IN  NUMBER,
  P_ID_BITACORA_OUT   OUT NUMBER
) IS
BEGIN
  INSERT INTO bitacora (
    id_bitacora, id_practica, fecha_actividad, actividad,
    descripcion, horas_reportadas, estado_validacion
  ) VALUES (
    NULL, P_ID_PRACTICA, P_FECHA_ACTIVIDAD, P_ACTIVIDAD,
    P_DESCRIPCION, P_HORAS, 'PENDIENTE'
  )
  RETURNING id_bitacora INTO P_ID_BITACORA_OUT;

  UPDATE practica
     SET horas_acumuladas = NVL(horas_acumuladas, 0) + P_HORAS,
         estado = CASE
                    WHEN NVL(horas_acumuladas, 0) + P_HORAS >= horas_objetivo
                    THEN 'PENDIENTE_APROBACION'
                    ELSE estado
                  END
   WHERE id_practica = P_ID_PRACTICA;
END;
/

CREATE OR REPLACE PROCEDURE SP_VALIDAR_ACTIVIDAD (
  P_ID_BITACORA       IN NUMBER,
  P_ID_DOCENTE        IN NUMBER,
  P_ESTADO_VALIDACION IN VARCHAR2,
  P_OBSERVACION       IN VARCHAR2
) IS
BEGIN
  UPDATE bitacora
     SET estado_validacion = P_ESTADO_VALIDACION,
         observacion_docente = P_OBSERVACION,
         id_docente_validador = P_ID_DOCENTE,
         fecha_validacion = SYSTIMESTAMP
   WHERE id_bitacora = P_ID_BITACORA;
END;
/

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_EVIDENCIA (
  P_ID_BITACORA       IN  NUMBER,
  P_NOMBRE_ARCHIVO    IN  VARCHAR2,
  P_TIPO_ARCHIVO      IN  VARCHAR2,
  P_URL_ARCHIVO       IN  VARCHAR2,
  P_ID_EVIDENCIA_OUT  OUT NUMBER
) IS
BEGIN
  INSERT INTO evidencia (
    id_evidencia, nombre_archivo, tipo_archivo, url_archivo, fecha_carga, id_actividad
  ) VALUES (
    NULL, P_NOMBRE_ARCHIVO, P_TIPO_ARCHIVO, P_URL_ARCHIVO, SYSTIMESTAMP, P_ID_BITACORA
  )
  RETURNING id_evidencia INTO P_ID_EVIDENCIA_OUT;
END;
/

CREATE OR REPLACE PROCEDURE SP_CERRAR_PRACTICA (
  P_ID_PRACTICA   IN NUMBER,
  P_ESTADO_FINAL  IN VARCHAR2
) IS
BEGIN
  UPDATE practica
     SET estado = P_ESTADO_FINAL,
         fecha_fin = NVL(fecha_fin, SYSDATE)
   WHERE id_practica = P_ID_PRACTICA;
END;
/

CREATE OR REPLACE PROCEDURE SP_CREAR_PLANTILLA_BITACORA (
  P_NOMBRE            IN  VARCHAR2,
  P_SEMESTRE          IN  NUMBER,
  P_MODALIDAD         IN  VARCHAR2,
  P_ID_CREADO_POR     IN  NUMBER,
  P_ID_PLANTILLA_OUT  OUT NUMBER
) IS
BEGIN
  INSERT INTO plantilla_bitacora (
    id_plantilla, nombre, semestre_practica, modalidad,
    version, estado, id_creado_por, fecha_creacion
  ) VALUES (
    NULL, P_NOMBRE, P_SEMESTRE, P_MODALIDAD,
    '1', 'ACTIVA', P_ID_CREADO_POR, SYSDATE
  )
  RETURNING id_plantilla INTO P_ID_PLANTILLA_OUT;
END;
