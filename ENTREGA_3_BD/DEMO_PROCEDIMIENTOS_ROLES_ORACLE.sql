PROMPT 1) ROLES DE APLICACION

DECLARE
  PROCEDURE create_role_if_missing(p_role VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM dba_roles WHERE role = UPPER(p_role);
    IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE ROLE ' || p_role;
    END IF;
  END;
BEGIN
  create_role_if_missing('ROL_SIGPRA_ESTUDIANTE');
  create_role_if_missing('ROL_SIGPRA_DOCENTE');
  create_role_if_missing('ROL_SIGPRA_DIRECTOR');
  create_role_if_missing('ROL_SIGPRA_AUDITOR');
END;
/

PROMPT 2) USUARIOS DE DEMOSTRACION

DECLARE
  PROCEDURE create_user_if_missing(p_user VARCHAR2, p_password VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM dba_users WHERE username = UPPER(p_user);
    IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'CREATE USER ' || p_user ||
        ' IDENTIFIED BY "' || p_password || '" DEFAULT TABLESPACE USERS TEMPORARY TABLESPACE TEMP';
      EXECUTE IMMEDIATE 'ALTER USER ' || p_user || ' QUOTA UNLIMITED ON USERS';
    END IF;
  END;
BEGIN
  create_user_if_missing('U_SIGPRA_EST', 'Sigpra2026*Est');
  create_user_if_missing('U_SIGPRA_DOC', 'Sigpra2026*Doc');
  create_user_if_missing('U_SIGPRA_DIR', 'Sigpra2026*Dir');
  create_user_if_missing('U_SIGPRA_AUD', 'Sigpra2026*Aud');
END;
/

